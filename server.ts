import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI } from "@google/genai";

const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

async function startServer() {
  const app = express();
  const PORT = 3000;

  // Middleware for parsing JSON with increased limit for base64 images
  app.use(express.json({ limit: "50mb" }));

  // API Route to generate mockup
  app.post("/api/generate-mockup", async (req, res) => {
    try {
      const { logoBase64, mimeType, prompt } = req.body;

      if (!logoBase64 || !mimeType || !prompt) {
        return res.status(400).json({ error: "Missing required fields" });
      }

      // Remove the data:image/*;base64, prefix if present
      const base64Data = logoBase64.replace(/^data:image\/\w+;base64,/, "");

      const response = await ai.models.generateContent({
        // model: "gemini-3.1-flash-lite-image", // using general image editing model
        model: "gemini-3.1-flash-image-preview",
        contents: {
          parts: [
            {
              inlineData: {
                data: base64Data,
                mimeType: mimeType,
              },
            },
            {
              text: prompt,
            },
          ],
        },
      });

      // Find the generated image in the response
      let imageUrl = null;
      if (response.candidates && response.candidates[0] && response.candidates[0].content && response.candidates[0].content.parts) {
        for (const part of response.candidates[0].content.parts) {
          if (part.inlineData) {
            imageUrl = `data:${part.inlineData.mimeType || "image/png"};base64,${part.inlineData.data}`;
            break;
          }
        }
      }

      if (imageUrl) {
        res.json({ imageUrl });
      } else {
        res.status(500).json({ error: "No image generated by the model." });
      }
    } catch (error: any) {
      console.error("Error generating mockup:", error);
      res.status(500).json({ error: error.message || "An error occurred while generating the mockup." });
    }
  });

  // Vite middleware for development
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server running on http://localhost:${PORT}`);
  });
}

startServer();
